"""
Writes the raven agent skill's language files (skills/raven/languages/*.md) and the plugin's
manifests (.claude-plugin/), from the headers, the bindings just generated, and one hand-written
snippet per language (skill/<language>.md).

Each language file shows a headless test (the snippet) and the driver's calls as that binding
spells them. A spelling is written only when the generated binding declares it, so the files can't
drift from the bindings; a call a binding leaves out is said to be missing.
"""

import json
import os
import re

import gen_c3
import gen_go
import gen_rust

HERE = os.path.dirname(os.path.abspath(__file__))

# The calls a test, a script or a preview makes, besides everything in raven_driver.h.
CORE = ["Rinit_ex", "Rset_animation_time_step", "Rerror_set_callback", "Rwait_idle", "Ris_idle",
        "Rwindow_save_preview", "Rshutdown"]

# key, title, the binding file (in bindings/), its spelling of a C function, how to find the
# declaration in it, and whether the language has a harness of its own.
LANGUAGES = [
    ("c", "C", None, lambda n: n, None, True),
    ("cpp", "C++", "cpp/raven.hpp", lambda n: "raven::" + gen_c3.snake(n), r"inline [^\n(]*\b{}\(", True),
    ("python", "Python", "python/raven.py", lambda n: "r." + n, r"^def {}\(", True),
    ("rust", "Rust", "rust/src/sys.rs", lambda n: n, r"pub fn {}\(", True),
    ("go", "Go", "go/raven/raven.go", lambda n: "raven." + gen_go.go_name(n), r"^func {}\(", False),
    ("csharp", "C#", "csharp/Raven.cs", lambda n: "R." + n, r"public static [^\n(]*\b{}\(", False),
    ("zig", "Zig", "zig/raven.zig", lambda n: "r." + n, r"pub extern fn {}\(", False),
    ("luajit", "LuaJIT", "luajit/raven.lua", lambda n: "r." + n, r"\b{}\(", False),
    ("java", "Java", "java/src/main/java/raven/R.java", lambda n: n, r"public static [^\n(]*\b{}\(", False),
    ("odin", "Odin", "odin/raven/raven.odin", lambda n: "r." + n, r"\t{} :: proc", False),
    ("bun", "Bun", "bun/src/raven.ts", lambda n: "r." + n, r"export function {}\(", False),
    ("node", "Node.js", "node/src/raven.d.ts", lambda n: "r." + n, r"export function {}\(", False),
    ("c3", "C3", "c3/raven.c3l/src/raven_c.c3", lambda n: "c::" + gen_c3.c_function(n), r"extern fn [^\n(]*\b{}\(", False),
]

# A binding's own way to make a call it doesn't wrap under the C name (its examples use these).
SUBSTITUTES = {
    "go": {"Rinit_ex": "raven.InitHeadless()  (the null backend, no window system)"},
    "cpp": {"Rwindow_save_preview": "raven::Window(window).save_preview(...)"},
}

HEADER = "<!-- Generated by tools/bindgen from tools/bindgen/skill/%s.md and the headers: do not edit. -->"

BY_HAND = """Without a harness in %(title)s, a test does by hand what C's `raven/raven_test.h` does:
the null backend with no window system, a fixed animation step, `Rwait_idle` before every find
and after every action, Raven's errors treated as failures (`Rerror_set_callback`), and
`Rshutdown` at the end. A check counts a selector that states what is expected (`text=`, a state),
since a count is a plain number in every binding."""


def driver_functions(api):
    names = [f.name for f in api.functions if f.header == "raven_driver.h"]
    return CORE + [n for n in names if n not in CORE]


def spelled(api, files, key, binding, spell, pattern):
    """(C name, this binding's spelling, or None when the binding doesn't declare it)."""
    text = files.get(binding, "") if binding else ""
    # (and the binding's hand-written files beside it, such as Go's callbacks.go)
    if binding:
        folder = os.path.join(os.path.dirname(os.path.dirname(HERE)), "bindings", os.path.dirname(binding))
        extension = os.path.splitext(binding)[1]
        for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
            path = os.path.join(folder, name)
            if name.endswith(extension) and name != os.path.basename(binding) and os.path.isfile(path):
                with open(path, encoding="utf-8") as f:
                    text += "\n" + f.read()
    substitutes = SUBSTITUTES.get(key, {})
    rows = []
    for name in driver_functions(api):
        if binding is None:
            rows.append((name, name))
            continue
        if name in substitutes:
            rows.append((name, substitutes[name]))
            continue
        local = spell(name)
        bare = re.sub(r"^.*(::|\.)", "", local)
        rows.append((name, local if re.search(pattern.format(re.escape(bare)), text, re.M) else None))
    return rows


def language_file(api, files, key, title, binding, spell, pattern, has_harness):
    with open(os.path.join(HERE, "skill", key + ".md"), encoding="utf-8") as f:
        snippet = f.read().strip()
    out = [HEADER % key, "", "# Raven in %s" % title, ""]
    if binding:
        out.append("The binding is `bindings/%s` in Raven's repository. Loading or linking it: Raven's "
                   "`bindings/README.md`, \"Per language\"." % binding)
    else:
        out.append("Include `<Raven.h>` and link `raven`. The driver is `raven/raven_driver.h`, included by `Raven.h`.")
    out += ["", "## A headless test", "", snippet, ""]
    if not has_harness:
        out += [BY_HAND % {"title": title}, ""]
    out += ["## The driver in %s" % title, "",
            "The calls of `raven/raven_driver.h`, and those a test, a script or a preview makes besides. "
            "What each takes and returns is in the header's comments.", ""]
    rows = spelled(api, files, key, binding, spell, pattern)
    if binding:
        missing = [name for name, local in rows if local is None]
        out += ["| C | %s |" % title, "|---|---|"]
        out += ["| `%s` | `%s` |" % (name, local) for name, local in rows if local]
        if missing:
            out += ["", "Not in this binding (call them through its C interop): %s." % ", ".join("`%s`" % n for n in missing)]
    else:
        out += ", ".join("`%s`" % name for name, _ in rows).split("\n")
    return "\n".join(out)


def generate(api, files):
    result = {}
    for key, title, binding, spell, pattern, has_harness in LANGUAGES:
        result["skills/raven/languages/%s.md" % key] = language_file(api, files, key, title, binding, spell, pattern, has_harness)
    version = gen_rust.package_version()
    description = "Preview, drive and test a Raven UI in C or any language Raven binds: the raven agent skill."
    result[".claude-plugin/plugin.json"] = json.dumps({
        "name": "raven",
        "version": version,
        "description": description,
        "repository": "https://github.com/oscar-soirey/Raven",
        "license": "Apache-2.0",
        "author": {"name": "Raven contributors", "url": "https://github.com/oscar-soirey/Raven"},
        "keywords": ["raven", "gui", "ui-testing", "preview", "skills"],
    }, indent=2)
    result[".claude-plugin/marketplace.json"] = json.dumps({
        "name": "raven",
        "owner": {"name": "Raven", "url": "https://github.com/oscar-soirey/Raven"},
        "description": "Raven's agent skill, as an installable Claude Code plugin.",
        "plugins": [{
            "name": "raven",
            "source": "./",
            "description": description,
            "author": {"name": "Raven contributors", "url": "https://github.com/oscar-soirey/Raven"},
            "category": "development",
            "keywords": ["raven", "gui", "ui-testing", "preview"],
        }],
    }, indent=2)
    return result
