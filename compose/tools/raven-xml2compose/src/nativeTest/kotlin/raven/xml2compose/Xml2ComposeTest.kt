package raven.xml2compose

import kotlinx.cinterop.cstr
import kotlinx.cinterop.memScoped
import kotlinx.cinterop.ptr
import kotlinx.cinterop.toKString
import platform.posix.getenv
import platform.posix.mkdtemp
import platform.posix.system
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertTrue

class Xml2ComposeTest {
    private val root: String = run {
        val base = getenv("TMPDIR")?.toKString()?.trimEnd('/') ?: "/tmp"
        memScoped { mkdtemp("$base/xml2compose-XXXXXX".cstr.ptr)!!.toKString() }
    }
    private val ui = "$root/ui"
    private val out = "$root/out"
    private val reported = mutableListOf<String>()

    @AfterTest
    fun removeTheFolder() {
        system("rm -rf '$root'")
    }

    private fun xml(path: String, text: String) {
        assertTrue(makeDirectories("$ui/$path".substringBeforeLast('/')) && writeText("$ui/$path", text), path)
    }

    private fun run(vararg extra: String): Int {
        reported.clear()
        return xml2compose(listOf(ui, "--out", out, "--package", "app.ui") + extra) { reported += it }
    }

    @Test
    fun itWritesOneFilePerXmlFileInSubfoldersAndSubpackages() {
        xml("main.xml", "<Window Title=\"Notes\"><Include Source=\"notes/list.xml\"/></Window>")
        xml("notes/list.xml", "<VBox><Label>Notes</Label></VBox>")
        assertEquals(0, run("--main", "main.xml"), reported.joinToString("\n"))
        assertEquals(emptyList(), reported)
        val main = readText("$out/Main.kt")!!
        assertTrue(main.startsWith("// Generated by raven-xml2compose from main.xml. Do not edit.\n"), main)
        assertTrue("import app.ui.notes.List\n" in main && "fun main() = singleWindowApplication(title = \"Notes\")" in main, main)
        assertTrue("package app.ui.notes\n" in readText("$out/notes/List.kt")!!)
    }

    @Test
    fun diagnosticsNameTheFileLineAndColumn() {
        xml("a.xml", "<VBox>\n<Gauge/>\n</VBox>")
        assertEquals(0, run())
        assertEquals(listOf("$ui/a.xml:2:1: warning: <Gauge> has no composable yet"), reported)
    }

    @Test
    fun werrorFailsOnAWarning() {
        xml("a.xml", "<VBox><Gauge/></VBox>")
        assertEquals(1, run("--werror"))
        assertEquals(0, run())
    }

    @Test
    fun anIncludeCycleFails() {
        xml("a.xml", "<VBox><Include Source=\"b.xml\"/></VBox>")
        xml("b.xml", "<VBox><Include Source=\"a.xml\"/></VBox>")
        assertEquals(1, run())
        assertEquals(listOf("$ui/b.xml:1:1: error: <Include Source=\"a.xml\"> is an include cycle: a.xml → b.xml → a.xml"), reported)
    }

    @Test
    fun aMainThatIsntThereFails() {
        xml("a.xml", "<VBox/>")
        assertEquals(1, run("--main", "main.xml"))
    }

    @Test
    fun aGeneratedFileIsOverwrittenAndAHandWrittenOneIsnt() {
        xml("a.xml", "<VBox/>")
        xml("b.xml", "<HBox/>")
        assertEquals(0, run())
        xml("a.xml", "<HBox/>")
        assertTrue(makeDirectories(out) && writeText("$out/B.kt", "// mine\n"))
        assertEquals(1, run())
        assertEquals(listOf("$out/B.kt:1:1: error: not overwritten: it wasn't generated by raven-xml2compose"), reported)
        assertTrue("Row(modifier)" in readText("$out/A.kt")!!)
        assertEquals("// mine\n", readText("$out/B.kt"))
    }

    @Test
    fun aWrongCommandLineIsExitCodeTwo() {
        assertEquals(2, xml2compose(listOf(ui, "--out", out)) { reported += it })
        assertEquals(listOf("usage: raven-xml2compose <dir> --out <dir> --package <name> [--main <file>] [--werror]"), reported)
        assertEquals(2, xml2compose(listOf("$root/none", "--out", out, "--package", "a")) { })
        assertEquals(2, xml2compose(listOf(ui, "--out", out, "--package", "not a package")) { })
        assertNull(readText("$out/A.kt"))
    }
}
