package raven.xml2compose

import platform.posix.fflush
import platform.posix.fputs
import platform.posix.stderr
import raven.compose.xml.GENERATED_HEADER
import raven.compose.xml.Severity
import raven.compose.xml.XmlFile
import raven.compose.xml.translateFolder
import raven.compose.xml.withHeadlessRaven
import kotlin.system.exitProcess

private const val USAGE = "usage: raven-xml2compose <dir> --out <dir> --package <name> [--main <file>] [--werror]"

fun main(args: Array<String>) {
    val code = xml2compose(args.toList()) { fputs(it + "\n", stderr) }
    fflush(stderr)
    exitProcess(code)
}

/** The tool's options, read from the command line. */
internal class Options(val input: String, val output: String, val packageName: String, val main: String?, val werror: Boolean)

/** Reads [args], or null with the reason given to [report]. */
internal fun options(args: List<String>, report: (String) -> Unit): Options? {
    var input: String? = null
    var output: String? = null
    var packageName: String? = null
    var main: String? = null
    var werror = false
    var i = 0
    fun value(flag: String): String? = args.getOrNull(++i) ?: null.also { report("$flag needs a value") }
    while (i < args.size) {
        when (val arg = args[i]) {
            "--out" -> output = value(arg) ?: return null
            "--package" -> packageName = value(arg) ?: return null
            "--main" -> main = value(arg) ?: return null
            "--werror" -> werror = true
            else -> when {
                arg.startsWith("-") -> return null.also { report("unknown option $arg") }
                input != null -> return null.also { report("one folder only: $input, then $arg") }
                else -> input = arg
            }
        }
        i++
    }
    if (input == null || output == null || packageName == null) return null.also { report(USAGE) }
    if (!Regex("[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)*").matches(packageName)) {
        return null.also { report("--package $packageName: not a package name") }
    }
    return Options(input.trimEnd('/').ifEmpty { "/" }, output.trimEnd('/').ifEmpty { "/" }, packageName, main, werror)
}

/**
 * The tool: translates every `.xml` file under the folder into a Kotlin file under `--out`, reports
 * to [report] as `file:line:column: severity: message`, and returns the exit code: 0, 1 when there
 * were errors (or warnings with `--werror`), 2 for a wrong command line. A file at an output path
 * that wasn't generated by the tool is never overwritten: that is an error.
 */
fun xml2compose(args: List<String>, report: (String) -> Unit): Int {
    val options = options(args, report) ?: return 2
    if (!isDirectory(options.input)) {
        report("${options.input}: not a folder")
        return 2
    }
    val files = xmlFiles(options.input).map { path ->
        XmlFile(path, readText("${options.input}/$path") ?: run {
            report("${options.input}/$path: can't be read")
            return 1
        })
    }
    val translation = withHeadlessRaven { translateFolder(files, options.packageName, options.main) }
    for (diagnostic in translation.diagnostics) report(diagnostic.format(options.input))
    var failed = translation.hasErrors || (options.werror && translation.hasWarnings)
    for (file in translation.files) {
        val path = "${options.output}/${file.path}"
        val existing = readText(path)
        if (existing != null && !existing.startsWith(GENERATED_HEADER)) {
            report("$path:1:1: ${Severity.Error.name.lowercase()}: not overwritten: it wasn't generated by raven-xml2compose")
            failed = true
            continue
        }
        if (existing == file.code) continue
        if (!makeDirectories(path.substringBeforeLast('/')) || !writeText(path, file.code)) {
            report("$path: can't be written")
            failed = true
        }
    }
    return if (failed) 1 else 0
}
