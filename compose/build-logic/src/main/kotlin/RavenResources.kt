import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

/** `ravenResources { }`: how the `raven.compose-resources` plugin treats `composeResources/`. */
abstract class RavenResourcesExtension {
    /** The package of `Res`; by default Compose's, `<group>.<module>.generated.resources`. */
    abstract val packageOfResClass: Property<String>

    /**
     * Builds every file into the executable (`registerResource`) instead of copying the folder beside
     * it, for a single-file app. Not built yet: Generated resources: embedding.
     */
    abstract val embed: Property<Boolean>
}

/** The kinds of resources, each a folder of `composeResources/`. */
internal enum class ResourceKind(val folder: String, val type: String?) {
    Drawable("drawable", "DrawableResource"),
    Font("font", "FontResource"),
}

/** Writes `Res` for the files of [resources]. */
abstract class GenerateResClass : DefaultTask() {
    @get:InputDirectory
    @get:Optional
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val resources: DirectoryProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val out = outputDirectory.get().asFile
        out.deleteRecursively()
        val root = resources.orNull?.asFile?.takeIf { it.isDirectory }
        val pkg = packageName.get()
        val file = File(out, pkg.replace('.', '/') + "/Res.kt")
        file.parentFile.mkdirs()
        file.writeText(resClassSource(pkg, root))
    }
}

/** Compose's rule for a file's identifier: its name without the extension, other characters `_`. */
internal fun resourceIdentifier(file: File): String {
    val name = file.nameWithoutExtension.map { if (it.isLetterOrDigit() || it == '_') it else '_' }.joinToString("")
    val identifier = if (name.firstOrNull()?.isDigit() != false) "_$name" else name
    return if (identifier in kotlinKeywords) "`$identifier`" else identifier
}

private val kotlinKeywords = setOf(
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
    "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while",
)

internal fun resClassSource(pkg: String, root: File?): String = buildString {
    appendLine("// Generated by the raven.compose-resources plugin from composeResources/. Don't edit.")
    appendLine("package $pkg")
    appendLine()
    appendLine("import raven.compose.ui.res.DrawableResource")
    appendLine("import raven.compose.ui.res.FontResource")
    appendLine("import raven.compose.ui.res.readResourceBytes")
    appendLine()
    appendLine("/** The files of composeResources/: drawable/ and font/ by name, files/ by path. */")
    appendLine("public object Res {")
    for (kind in ResourceKind.entries) {
        val files = root?.let { File(it, kind.folder) }?.listFiles()?.filter { it.isFile && !it.isHidden }?.sortedBy { it.name }.orEmpty()
        val byName = files.groupBy { resourceIdentifier(it) }
        byName.entries.firstOrNull { it.value.size > 1 }?.let { (name, clash) ->
            throw GradleException(
                "composeResources/${kind.folder}: ${clash.joinToString(" and ") { it.name }} both become Res.${kind.folder}.$name; rename one",
            )
        }
        appendLine("    public object ${kind.folder} {")
        for ((name, same) in byName) {
            appendLine("        public val $name: ${kind.type} = ${kind.type}(\"${kind.folder}/${same.single().name}\")")
        }
        appendLine("    }")
        appendLine()
    }
    appendLine("    /** The bytes of the file at [path] under composeResources/, such as \"files/notes.txt\". */")
    appendLine("    public suspend fun readBytes(path: String): ByteArray = readResourceBytes(path)")
    appendLine("}")
}
