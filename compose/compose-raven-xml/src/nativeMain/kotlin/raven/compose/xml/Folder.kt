package raven.compose.xml

/** One XML file of a folder: its [path] inside the folder, `/`-separated, and its [text]. */
public class XmlFile(public val path: String, public val text: String)

/** A generated Kotlin file: [path] inside the output folder, its [packageName], and its [code]. */
public class KotlinFile(
    /** The XML file it was translated from, as [XmlFile.path]. */
    public val source: String,
    public val path: String,
    public val packageName: String,
    /** The whole file, starting with [GENERATED_HEADER]. */
    public val code: String,
)

public enum class Severity { Warning, Error }

/** One thing to report about [path] (an [XmlFile.path]); [column] is 0 when only the line is known. */
public data class Diagnostic(
    val path: String,
    val line: Int,
    val column: Int,
    val message: String,
    val severity: Severity,
) {
    /** `path:line:column: warning: message`, with the folder's path in front of [path] when given. */
    public fun format(folder: String? = null): String {
        val file = if (folder == null) path else folder.trimEnd('/') + "/" + path
        return "$file:${maxOf(line, 1)}:${maxOf(column, 1)}: ${severity.name.lowercase()}: $message"
    }

    override fun toString(): String = format()
}

/** The Kotlin files of a folder's translation, and what was reported on the way. */
public class FolderTranslation(public val files: List<KotlinFile>, public val diagnostics: List<Diagnostic>) {
    public val hasErrors: Boolean get() = diagnostics.any { it.severity == Severity.Error }
    public val hasWarnings: Boolean get() = diagnostics.any { it.severity == Severity.Warning }
}

/** How every generated file starts; only files that start so are overwritten. */
public const val GENERATED_HEADER: String = "// Generated by raven-xml2compose from "

/**
 * Translates a folder of Raven XML files into Kotlin, one file each, named in PascalCase after the
 * XML file (`now_playing.xml` becomes `NowPlaying.kt`). A file in a subfolder is in a subpackage of
 * [packageName] (`notes/notes.xml` under `app.ui` is in `app.ui.notes`), and goes to that subfolder.
 *
 * A file whose root is an element also becomes a composable named after it, which an
 * `<Include Source>` calls. The declarations of the files a file includes are known in it, and, as
 * Raven finds them where it looks for files, those of every file of declarations only next to it or
 * in its subfolders. Includes
 * resolve against the including file's folder, then the folder's root; each file is translated
 * once, and an include cycle is an error. `main()` is generated only for [main], a file whose root
 * is `<Window>`.
 *
 * Raven must be running, and this called on its UI thread: it parses with Raven ([withHeadlessRaven]).
 */
public fun translateFolder(files: List<XmlFile>, packageName: String, main: String? = null): FolderTranslation =
    FolderTranslator(files, packageName, main).run()

private class XmlUnit(val file: XmlFile) {
    val folder: String = file.path.substringBeforeLast('/', "")
    val baseName: String = file.path.substringAfterLast('/').removeSuffix(".xml")
    var root: XmlElement? = null
    var state = State.New
    var translator: Translator? = null

    /** Included paths that close a cycle, which this file mustn't wait for. */
    val cyclic = mutableSetOf<String>()

    enum class State { New, Visiting, Done }
}

private class FolderTranslator(files: List<XmlFile>, private val packageName: String, private val main: String?) {
    private val units = files.sortedBy { it.path }.associate { it.path to XmlUnit(it) }
    private val diagnostics = mutableListOf<Diagnostic>()
    private val outputs = mutableListOf<KotlinFile>()

    fun run(): FolderTranslation {
        for (unit in units.values) parse(unit)
        if (main != null) {
            val root = units[main]?.root
            when {
                main !in units -> error(main, 0, "--main $main: no such file in the folder")
                root != null && !root.tag.equals("Window", ignoreCase = true) -> error(main, root.line, "--main $main: its root is <${root.tag}>, not <Window>")
            }
        }
        val taken = mutableMapOf<String, String>()
        for (unit in units.values) {
            val output = outputPath(unit)
            val other = taken.put(output.lowercase(), unit.file.path)
            if (other != null) error(unit.file.path, 0, "becomes $output, as $other does")
        }
        for (unit in units.values) translate(unit)
        return FolderTranslation(outputs.sortedBy { it.path }, diagnostics.toList())
    }

    private fun parse(unit: XmlUnit) {
        unit.root = try {
            parseRavenXml(unit.file.text)
        } catch (e: XmlParseException) {
            diagnostics += Diagnostic(unit.file.path, e.line, e.column, e.reason, Severity.Error)
            null
        }
    }

    /** Translates [unit] after the files it includes, depth first; a file being translated closes a cycle. */
    private fun translate(unit: XmlUnit) {
        if (unit.state != XmlUnit.State.New) return
        unit.state = XmlUnit.State.Visiting
        val root = unit.root
        val included = LinkedHashMap<String, WidgetFunction>()
        if (root != null && !isDeclarations(root)) {
            // Raven registers declarations for the whole app, and finds files of them where it looks
            // for files, next to the XML file and in its subfolders: those are known here, included or not.
            for (declarations in units.values) {
                val other = declarations.root ?: continue
                if (!isDeclarations(other) || declarations.state == XmlUnit.State.Visiting) continue
                if (!within(declarations.folder, unit.folder)) continue
                translate(declarations)
                collect(declarations, included, mutableSetOf(unit.file.path))
            }
        }
        if (root != null) {
            for (include in includes(root)) {
                val source = include.attributes.entries.firstOrNull { it.key.equals("Source", ignoreCase = true) }?.value ?: continue
                val target = resolve(unit, source)?.let { units.getValue(it) } ?: continue
                when (target.state) {
                    XmlUnit.State.Visiting -> {
                        unit.cyclic += target.file.path
                        error(unit.file.path, include.line, "<Include Source=\"$source\"> is an include cycle: ${cycle(target, unit)}")
                    }
                    else -> translate(target)
                }
                if (target.file.path !in unit.cyclic) collect(target, included, mutableSetOf(unit.file.path))
            }
        }
        unit.state = XmlUnit.State.Done
        if (root == null) return
        val pkg = packageOf(unit)
        val translator = Translator(
            FileContext(pkg, fileName(unit.baseName), main == unit.file.path, included) { source -> target(unit, source) },
        )
        unit.translator = translator
        val translation = translator.run(root)
        for (warning in translation.warnings) {
            diagnostics += Diagnostic(unit.file.path, warning.line, warning.column, warning.message, Severity.Warning)
        }
        val code = buildString {
            append(GENERATED_HEADER).append(unit.file.path).append(". Do not edit.\n\n")
            append("package ").append(pkg).append("\n")
            if (translation.code.isNotEmpty()) append("\n").append(translation.code)
        }
        outputs += KotlinFile(unit.file.path, outputPath(unit), pkg, code)
    }

    /** The declarations [unit] brings in: its own and those of what it includes, by lowercased tag. */
    private fun collect(unit: XmlUnit, into: MutableMap<String, WidgetFunction>, seen: MutableSet<String>) {
        if (!seen.add(unit.file.path)) return
        val root = unit.root ?: return
        for (include in includes(root)) {
            val source = include.attributes.entries.firstOrNull { it.key.equals("Source", ignoreCase = true) }?.value ?: continue
            val path = resolve(unit, source) ?: continue
            if (path !in unit.cyclic) collect(units.getValue(path), into, seen)
        }
        val pkg = packageOf(unit)
        for (function in unit.translator?.declared.orEmpty()) {
            into[function.xmlName.lowercase()] = WidgetFunction(
                function.xmlName, function.name, function.root, function.params, function.slots, function.rootLayout, pkg,
            )
        }
    }

    private fun target(unit: XmlUnit, source: String): IncludeTarget {
        val path = resolve(unit, source) ?: return IncludeTarget.Missing("no such file in the folder")
        if (path in unit.cyclic) return IncludeTarget.Cycle
        val target = units.getValue(path)
        val root = target.root ?: return IncludeTarget.Missing("$path couldn't be read")
        return IncludeTarget.File(target.translator?.composable, root.tag)
    }

    /** The included file's path: next to the including file, else from the folder's root. */
    private fun resolve(unit: XmlUnit, source: String): String? {
        val nextTo = normalize(if (unit.folder.isEmpty()) source else "${unit.folder}/$source")
        if (nextTo != null && nextTo in units) return nextTo
        return normalize(source)?.takeIf { it in units }
    }

    /** The path from [from] back to [to] along the includes being translated, for the message. */
    private fun cycle(from: XmlUnit, to: XmlUnit): String {
        val path = mutableListOf(from.file.path)
        fun walk(unit: XmlUnit): Boolean {
            if (unit === to) return true
            val root = unit.root ?: return false
            for (include in includes(root)) {
                val source = include.attributes.entries.firstOrNull { it.key.equals("Source", ignoreCase = true) }?.value ?: continue
                val next = resolve(unit, source)?.let { units.getValue(it) } ?: continue
                if (next.state != XmlUnit.State.Visiting || next.file.path in path) continue
                path += next.file.path
                if (walk(next)) return true
                path.removeAt(path.lastIndex)
            }
            return false
        }
        walk(from)
        return (path + from.file.path).joinToString(" → ")
    }

    private fun packageOf(unit: XmlUnit): String =
        if (unit.folder.isEmpty()) packageName else packageName + "." + unit.folder.split('/').joinToString(".", transform = ::packageSegment)

    private fun outputPath(unit: XmlUnit): String {
        val name = fileName(unit.baseName) + ".kt"
        return if (unit.folder.isEmpty()) name else unit.folder.split('/').joinToString("/", transform = ::packageSegment) + "/" + name
    }

    private fun error(path: String, line: Int, message: String) {
        diagnostics += Diagnostic(path, line, 0, message, Severity.Error)
    }
}

/** A file's name as the composable's and the Kotlin file's: `now_playing` becomes `NowPlaying`. */
private fun fileName(baseName: String): String = pascalCase(baseName.replace('_', '-'))

/** Whether [folder] is [parent] or one of its subfolders. */
private fun within(folder: String, parent: String): Boolean =
    parent.isEmpty() || folder == parent || folder.startsWith("$parent/")

/** Whether [root] only declares tags: `<Widgets>` or a single `<Widget>`. */
private fun isDeclarations(root: XmlElement): Boolean =
    root.tag.equals("Widgets", ignoreCase = true) || root.tag.equals("Widget", ignoreCase = true)

/** Every `<Include>` in [root], in document order. */
private fun includes(root: XmlElement): List<XmlElement> = buildList {
    fun walk(element: XmlElement) {
        if (element.isComment) return
        if (element.tag.equals("Include", ignoreCase = true)) add(element)
        element.children.forEach(::walk)
    }
    walk(root)
}

/** `a/./b/../c.xml` as `a/c.xml`; null when it climbs out of the folder. */
private fun normalize(path: String): String? {
    val parts = mutableListOf<String>()
    for (part in path.replace('\\', '/').split('/')) {
        when (part) {
            "", "." -> {}
            ".." -> if (parts.isEmpty()) return null else parts.removeAt(parts.lastIndex)
            else -> parts += part
        }
    }
    return parts.joinToString("/").ifEmpty { null }
}

/** A folder's name as a package segment: `now-playing` becomes `now_playing`, a keyword gains `_`. */
internal fun packageSegment(name: String): String {
    val segment = name.lowercase().replace(Regex("[^a-z0-9_]"), "_").ifEmpty { "_" }
    return when {
        segment.first().isDigit() -> "_$segment"
        segment in packageKeywords -> "${segment}_"
        else -> segment
    }
}

private val packageKeywords = setOf(
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
    "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while",
)
