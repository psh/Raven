package raven.compose.xml

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class FolderTest {
    private fun translate(main: String? = null, vararg files: Pair<String, String>): FolderTranslation =
        withHeadlessRaven { translateFolder(files.map { XmlFile(it.first, it.second) }, "app.ui", main) }

    private fun FolderTranslation.file(path: String): KotlinFile = files.single { it.path == path }

    @Test
    fun eachFileBecomesAFileNamedInPascalCaseWithItsComposable() {
        val result = translate(null, "now_playing.xml" to "<VBox><Label>Song</Label></VBox>")
        val file = result.file("NowPlaying.kt")
        assertEquals("now_playing.xml", file.source)
        assertEquals("app.ui", file.packageName)
        assertTrue(file.code.startsWith("// Generated by raven-xml2compose from now_playing.xml. Do not edit.\n\npackage app.ui\n\n"), file.code)
        assertTrue("@Composable\nfun NowPlaying(modifier: Modifier = Modifier) {\n    Column(modifier) {" in file.code, file.code)
        assertEquals(emptyList(), result.diagnostics)
    }

    @Test
    fun subfoldersAreSubpackages() {
        val result = translate(null, "notes/now-playing/list.xml" to "<VBox/>")
        val file = result.file("notes/now_playing/List.kt")
        assertEquals("app.ui.notes.now_playing", file.packageName)
        assertTrue("package app.ui.notes.now_playing\n" in file.code, file.code)
    }

    @Test
    fun anIncludeIsACallPlacedByTheIncludedRoot() {
        val result = translate(
            null,
            "page.xml" to "<VBox><Include Source=\"parts/header.xml\"/></VBox>",
            "parts/header.xml" to "<HBox Height=\"56\"><Label>Title</Label></HBox>",
        )
        val page = result.file("Page.kt").code
        assertTrue("import app.ui.parts.Header\n" in page, page)
        assertTrue("    Column(modifier) {\n        Header(modifier = Modifier.fillMaxWidth().height(56.dp))\n    }" in page, page)
        val header = result.file("parts/Header.kt").code
        assertTrue("fun Header(modifier: Modifier = Modifier) {\n    Row(modifier) {" in header, header)
        assertEquals(emptyList(), result.diagnostics)
    }

    @Test
    fun anIncludedFilesDeclarationsAreKnownAndImported() {
        val result = translate(
            null,
            "screen.xml" to "<VBox><Include Source=\"lib/widgets.xml\"/><Badge Text=\"hi\"/></VBox>",
            "lib/widgets.xml" to "<Widgets><Widget Name=\"Badge\" Text=\"new\"><Label Text=\"{Text}\"/></Widget></Widgets>",
        )
        val screen = result.file("Screen.kt").code
        assertTrue("import app.ui.lib.Badge\n" in screen, screen)
        assertTrue("// raven-xml: <Include Source=\"lib/widgets.xml\"/> brings in its declarations" in screen, screen)
        assertTrue("Badge(modifier = Modifier.fillMaxWidth(), text = \"hi\")" in screen, screen)
        // Declared once, in the file of declarations, which has no composable of its own.
        val widgets = result.file("lib/Widgets.kt").code
        assertTrue("fun Badge(modifier: Modifier = Modifier, text: String = \"new\")" in widgets, widgets)
        assertFalse("fun Widgets(" in widgets, widgets)
        assertFalse("fun Badge(" in screen, screen)
        assertEquals(emptyList(), result.diagnostics)
    }

    @Test
    fun aFileOfDeclarationsNextToAFileOrBelowIsKnownWithoutAnInclude() {
        val result = translate(
            null,
            "music/settings.xml" to "<VBox><Row2/></VBox>",
            "music/widgets.xml" to "<Widgets><Widget Name=\"Row2\"><Label>row</Label></Widget></Widgets>",
            "other/page.xml" to "<VBox><Row2/></VBox>",
        )
        assertTrue("Row2(modifier = Modifier.fillMaxWidth())" in result.file("music/Settings.kt").code)
        // Not from a folder beside it.
        assertEquals(listOf("other/page.xml:1:1: warning: <Row2> has no composable yet"), result.diagnostics.map { it.toString() })
    }

    @Test
    fun aSharedFileIsTranslatedOnce() {
        val result = translate(
            null,
            "a.xml" to "<VBox><Include Source=\"shared.xml\"/></VBox>",
            "b.xml" to "<HBox><Include Source=\"shared.xml\"/></HBox>",
            "shared.xml" to "<Label>shared</Label>",
        )
        assertEquals(listOf("A.kt", "B.kt", "Shared.kt"), result.files.map { it.path })
        assertTrue("Shared(modifier = Modifier.fillMaxWidth())" in result.file("A.kt").code)
        assertTrue("Shared(modifier = Modifier.fillMaxHeight())" in result.file("B.kt").code)
    }

    @Test
    fun mainIsOnlyForTheWindowGivenAsMain() {
        val result = translate(
            "main.xml",
            "main.xml" to "<Window Title=\"App\"><Include Source=\"body.xml\"/></Window>",
            "other.xml" to "<Window Title=\"Other\"><VBox/></Window>",
            "body.xml" to "<VBox><Label>Hi</Label></VBox>",
        )
        val main = result.file("Main.kt").code
        assertTrue("@Composable\nfun Main() {\n    Body(modifier = Modifier.fillMaxSize())\n}" in main, main)
        assertTrue("fun main() = singleWindowApplication(title = \"App\") {\n    Main()\n}" in main, main)
        val other = result.file("Other.kt").code
        assertTrue("fun Other() {" in other, other)
        assertFalse("fun main()" in other, other)
        assertFalse(result.hasErrors)
    }

    @Test
    fun aMainThatIsntAWindowIsAnError() {
        val result = translate("body.xml", "body.xml" to "<VBox/>")
        assertEquals(listOf("body.xml:1:1: error: --main body.xml: its root is <VBox>, not <Window>"), result.diagnostics.map { it.toString() })
        assertTrue(translate("gone.xml", "body.xml" to "<VBox/>").hasErrors)
    }

    @Test
    fun anIncludeCycleIsAnError() {
        val result = translate(
            null,
            "a.xml" to "<VBox><Include Source=\"b.xml\"/></VBox>",
            "b.xml" to "<VBox>\n<Include Source=\"a.xml\"/></VBox>",
        )
        assertEquals(
            listOf("b.xml:2:1: error: <Include Source=\"a.xml\"> is an include cycle: a.xml → b.xml → a.xml"),
            result.diagnostics.map { it.toString() },
        )
        assertTrue("// TODO(raven-xml): <Include Source=\"a.xml\"> is part of an include cycle" in result.file("B.kt").code)
        assertTrue("B(modifier = Modifier.fillMaxWidth())" in result.file("A.kt").code)
    }

    @Test
    fun aMissingIncludeIsAWarning() {
        val result = translate(null, "a.xml" to "<VBox><Include Source=\"nope.xml\"/></VBox>")
        assertEquals(listOf("a.xml:1:1: warning: <Include Source=\"nope.xml\">: no such file in the folder"), result.diagnostics.map { it.toString() })
    }

    @Test
    fun aFileThatDoesntParseIsAnErrorWithItsColumn() {
        val result = translate(null, "bad.xml" to "<VBox>", "good.xml" to "<VBox/>")
        val error = result.diagnostics.single()
        assertEquals(Severity.Error, error.severity)
        assertEquals("bad.xml", error.path)
        assertTrue(error.column > 0, error.toString())
        assertEquals(listOf("Good.kt"), result.files.map { it.path })
    }

    @Test
    fun twoFilesBecomingTheSameFileIsAnError() {
        val result = translate(null, "now-playing.xml" to "<VBox/>", "now_playing.xml" to "<VBox/>")
        assertEquals(
            listOf("now_playing.xml:1:1: error: becomes NowPlaying.kt, as now-playing.xml does"),
            result.diagnostics.map { it.toString() },
        )
    }

    @Test
    fun theComposableKeepsClearOfTheFilesDeclarationsAndTheVocabulary() {
        val result = translate(
            null,
            "button.xml" to "<VBox/>",
            "card.xml" to "<VBox><Widget Name=\"Card\"><Label/></Widget><Card/></VBox>",
        )
        assertTrue("fun ButtonUi(modifier: Modifier = Modifier)" in result.file("Button.kt").code)
        assertTrue("fun CardUi(modifier: Modifier = Modifier)" in result.file("Card.kt").code)
    }

    @Test
    fun theFolderCanBeAPathFrontOfEachDiagnostic() {
        val diagnostic = Diagnostic("a/b.xml", 3, 0, "oops", Severity.Warning)
        assertEquals("ui/a/b.xml:3:1: warning: oops", diagnostic.format("ui/"))
    }
}
