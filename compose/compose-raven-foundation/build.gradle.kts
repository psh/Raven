plugins {
    id("raven.native-target")
    alias(libs.plugins.kotlin.compose)
}

// The tests read their fixtures (Google's icons) where they are, at a path written into them.
val testResources = layout.projectDirectory.dir("src/nativeTest/resources")
val testResourcesSource = layout.buildDirectory.dir("generated/testResources/kotlin")

val generateTestResources = tasks.register("generateTestResources") {
    description = "Writes the path of src/nativeTest/resources into the tests, as TEST_RESOURCES."
    val directory = testResources.asFile.absolutePath
    val output = testResourcesSource
    inputs.property("directory", directory)
    outputs.dir(output)
    doLast {
        val file = output.get().file("raven/compose/foundation/TestResources.kt").asFile
        file.parentFile.mkdirs()
        val literal = directory.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        file.writeText(
            """
            |package raven.compose.foundation
            |
            |/** src/nativeTest/resources, the tests' fixtures. Generated by Gradle. */
            |internal const val TEST_RESOURCES: String = "$literal"
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    sourceSets.nativeMain.dependencies {
        api(project(":compose-raven-ui"))
        // ScrollState and LazyListState are rememberSaveable.
        api(libs.compose.runtime.saveable)
        // DatePicker and TimePicker are controlled by its LocalDate and LocalTime.
        api(libs.kotlinx.datetime)
        implementation(project(":compose-raven-native"))
    }
    sourceSets.nativeTest {
        kotlin.srcDir(generateTestResources)
        dependencies { implementation(project(":compose-raven-test")) }
    }
    // Foundation is built on compose-raven-ui's binding layer.
    sourceSets.all { languageSettings.optIn("raven.compose.ui.InternalComposeRavenApi") }
}
