import org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget
import org.jetbrains.kotlin.konan.target.HostManager

plugins {
    id("raven.native-target")
    alias(libs.plugins.kotlin.compose)
}

// The Vulkan headers of the sample's cinterop, local to it: compose-raven-vulkan ships no Vulkan
// bindings. By default, the headers Raven's own build found or fetched for libraven
// (RAVEN_VULKAN_INCLUDE_DIR, cmake/RavenVulkanHeaders.cmake), so the sample is compiled against the
// Vulkan Raven is; -PravenVulkanInclude=<folder holding vulkan/vulkan.h> names others, such as a
// Vulkan SDK's or the system's vulkan-headers.
val ravenBuildDir = rootProject.layout.buildDirectory.dir("raven/${HostManager.host.name}")
val vulkanInclude: Provider<String> = providers.gradleProperty("ravenVulkanInclude")
    .orElse(ravenBuildDir.map { it.dir("_deps/raven_vulkan_headers-src/include").asFile.absolutePath })

// The sample reads the SPIR-V of Raven's examples/viewport_vulkan where it is, shaders_spv.h.
val vulkanExample = rootProject.layout.projectDirectory.dir("../examples/viewport_vulkan")
val exampleDirSource = layout.buildDirectory.dir("generated/exampleDir/kotlin")

val generateExampleDir = tasks.register("generateExampleDir") {
    description = "Writes the path of Raven's examples/viewport_vulkan into the sample, as EXAMPLE_DIR."
    val directory = vulkanExample.asFile.absolutePath
    val output = exampleDirSource
    inputs.property("directory", directory)
    outputs.dir(output)
    doLast {
        val file = output.get().file("raven/sample/viewportvulkan/ExampleDir.kt").asFile
        file.parentFile.mkdirs()
        val literal = directory.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        file.writeText(
            """
            |package raven.sample.viewportvulkan
            |
            |/** Raven's examples/viewport_vulkan, whose shaders_spv.h the sample reads. Generated by Gradle. */
            |internal const val EXAMPLE_DIR: String = "$literal"
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    targets.withType<KotlinNativeTarget>().configureEach {
        compilations.getByName("main").cinterops.create("vulkan") {
            definitionFile.set(layout.projectDirectory.file("src/nativeInterop/cinterop/vulkan.def"))
            includeDirs(vulkanInclude.get())
        }
        binaries.executable {
            entryPoint = "raven.sample.viewportvulkan.main"
            baseName = "viewport-vulkan"
        }
    }
    sourceSets.nativeMain {
        kotlin.srcDir(generateExampleDir)
        dependencies { implementation(project(":compose-raven-vulkan")) }
        dependencies { implementation(project(":compose-raven-foundation")) }
    }
    sourceSets.nativeTest {
        dependencies {
            implementation(project(":compose-raven-test"))
            implementation(project(":compose-raven-native"))
        }
    }
}

// Raven's configure step fetches the headers when no SDK has them; without them, say what to do.
tasks.matching { it.name.startsWith("cinteropVulkan") }.configureEach {
    dependsOn(":compose-raven-native:configureRaven")
    val include = vulkanInclude
    doFirst {
        if (!File(include.get(), "vulkan/vulkan.h").isFile) {
            throw GradleException(
                "samples/viewport-vulkan: no vulkan/vulkan.h in ${include.get()}. Build compose-raven-native " +
                    "first (its CMake step finds or fetches the Vulkan headers), or pass " +
                    "-PravenVulkanInclude=<folder holding vulkan/vulkan.h> (a Vulkan SDK's include folder, " +
                    "or /usr/include with Linux's vulkan-headers).",
            )
        }
    }
}
