plugins {
    id("raven.native-target")
    alias(libs.plugins.kotlin.compose)
    // The pages' NavKeys are @Serializable.
    alias(libs.plugins.kotlin.serialization)
}

// The sample reads the C example's theme files and covers where they are, as it does with
// RAVEN_EXAMPLE_DIR.
val examples = rootProject.layout.projectDirectory.dir("../examples/music")
val exampleDirSource = layout.buildDirectory.dir("generated/exampleDir/kotlin")

val generateExampleDir = tasks.register("generateExampleDir") {
    description = "Writes the path of Raven's examples/music into the sample, as EXAMPLE_DIR."
    val directory = examples.asFile.absolutePath
    val output = exampleDirSource
    inputs.property("directory", directory)
    outputs.dir(output)
    doLast {
        val file = output.get().file("raven/sample/music/ExampleDir.kt").asFile
        file.parentFile.mkdirs()
        val literal = directory.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        file.writeText(
            """
            |package raven.sample.music
            |
            |/** Raven's examples/music, whose theme files and covers the sample reads. Generated by Gradle. */
            |internal const val EXAMPLE_DIR: String = "$literal"
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    targets.withType<org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget>().configureEach {
        binaries.executable {
            entryPoint = "raven.sample.music.main"
            baseName = "music"
        }
    }
    sourceSets.nativeMain {
        kotlin.srcDir(generateExampleDir)
        dependencies {
            implementation(project(":compose-raven-foundation"))
            implementation(project(":compose-raven-navigation3"))
            // Raven's image decoder, for the colours of the covers.
            implementation(project(":compose-raven-native"))
        }
    }
    // foundation's test harness, until it moves to compose-raven-test
    sourceSets.nativeTest {
        kotlin.srcDir(project(":compose-raven-foundation").file("src/testHarness/kotlin"))
        dependencies { implementation(project(":compose-raven-native")) }
    }
}
