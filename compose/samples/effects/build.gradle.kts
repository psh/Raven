plugins {
    id("raven.native-target")
    alias(libs.plugins.kotlin.compose)
}

// The sample reads the files of Raven's examples/effects where they are, as the C example does with
// RAVEN_EXAMPLE_DIR: the application's two shaders, wave.spv and liquid.spv.
val effectsExample = rootProject.layout.projectDirectory.dir("../examples/effects")
val exampleDirSource = layout.buildDirectory.dir("generated/exampleDir/kotlin")

val generateExampleDir = tasks.register("generateExampleDir") {
    description = "Writes the path of Raven's examples/effects into the sample, as EXAMPLE_DIR."
    val directory = effectsExample.asFile.absolutePath
    val output = exampleDirSource
    inputs.property("directory", directory)
    outputs.dir(output)
    doLast {
        val file = output.get().file("raven/sample/effects/ExampleDir.kt").asFile
        file.parentFile.mkdirs()
        val literal = directory.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        file.writeText(
            """
            |package raven.sample.effects
            |
            |/** Raven's examples/effects, whose wave.spv and liquid.spv the sample reads. Generated by Gradle. */
            |internal const val EXAMPLE_DIR: String = "$literal"
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    targets.withType<org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget>().configureEach {
        binaries.executable {
            entryPoint = "raven.sample.effects.main"
            baseName = "effects"
        }
    }
    sourceSets.nativeMain {
        kotlin.srcDir(generateExampleDir)
        dependencies { implementation(project(":compose-raven-foundation")) }
    }
    sourceSets.nativeTest {
        dependencies {
            implementation(project(":compose-raven-test"))
            implementation(project(":compose-raven-native"))
        }
    }
}
