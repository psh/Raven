plugins {
    id("raven.native-target")
    alias(libs.plugins.kotlin.compose)
}

// The sample reads the files of Raven's examples/themes where they are, as the C example does with
// RAVEN_EXAMPLE_DIR: the theme files, which Raven reloads when they change, and notes.md.
val themesExample = rootProject.layout.projectDirectory.dir("../examples/themes")
val exampleDirSource = layout.buildDirectory.dir("generated/exampleDir/kotlin")

val generateExampleDir = tasks.register("generateExampleDir") {
    description = "Writes the path of Raven's examples/themes into the sample, as EXAMPLE_DIR."
    val directory = themesExample.asFile.absolutePath
    val output = exampleDirSource
    inputs.property("directory", directory)
    outputs.dir(output)
    doLast {
        val file = output.get().file("raven/sample/themes/ExampleDir.kt").asFile
        file.parentFile.mkdirs()
        val literal = directory.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        file.writeText(
            """
            |package raven.sample.themes
            |
            |/** Raven's examples/themes, whose theme files and notes.md the sample reads. Generated by Gradle. */
            |internal const val EXAMPLE_DIR: String = "$literal"
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    targets.withType<org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget>().configureEach {
        binaries.executable {
            entryPoint = "raven.sample.themes.main"
            baseName = "themes"
        }
    }
    sourceSets.nativeMain {
        kotlin.srcDir(generateExampleDir)
        dependencies { implementation(project(":compose-raven-foundation")) }
    }
    // foundation's test harness, until it moves to compose-raven-test
    sourceSets.nativeTest {
        kotlin.srcDir(project(":compose-raven-foundation").file("src/testHarness/kotlin"))
        dependencies { implementation(project(":compose-raven-native")) }
    }
}
